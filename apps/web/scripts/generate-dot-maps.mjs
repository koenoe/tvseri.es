/**
 * Generates the country dot map dataset,
 * src/app/(site)/country/_data/dotMap/dataset.ts, from Natural Earth's admin-0
 * countries (1:50m, public domain). Download the GeoJSON yourself (it is not
 * committed), then:
 *
 *   node apps/web/scripts/generate-dot-maps.mjs <ne_50m_admin_0_countries.geojson>
 *   pnpm format-and-lint:fix
 *
 * It takes a few minutes: every cell of two world grids is a point-in-polygon
 * test. The dataset is one run-length world grid per window variant (a grid
 * value per cell: sea, land of no ISO country, or a country), brotli-packed,
 * plus each country's window: its top-left cell in that grid, or, for a
 * country too small to show at world scale, its own zoomed-in window.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { brotliCompressSync, constants } from 'node:zlib';

import {
  CELL,
  encodeRuns,
  ensureOwnDot,
  extractWindow,
  FIRST_COUNTRY,
  markOwn,
  OTHER_LAND,
  pickZoom,
  WINDOWS,
  windowOrigin,
  ZOOM,
} from '../src/app/(site)/country/_data/dotMap/grid.ts';
import {
  prepareShapes,
  rasterise,
  toCell,
  worldGrid,
} from '../src/app/(site)/country/_data/dotMap/rasterise.ts';

const source = process.argv[2];
if (!source) {
  console.error('Usage: generate-dot-maps.mjs <admin-0 countries GeoJSON>');
  process.exit(1);
}
const target = path.resolve(
  import.meta.dirname,
  '../src/app/(site)/country/_data/dotMap/dataset.ts',
);

/**
 * The ISO 3166-1 alpha-2 code, or undefined. Natural Earth writes -99 where a
 * code is disputed or shared (France, Norway); ISO_A2_EH has the fallback.
 * User-assigned codes (Kosovo's XK) have no landing.
 */
const isoCode = (properties) => {
  const code = [properties.ISO_A2_EH, properties.ISO_A2].find((value) =>
    /^[A-Z]{2}$/.test(value ?? ''),
  );
  return code && !code.startsWith('X') ? code : undefined;
};

const { features } = JSON.parse(readFileSync(source, 'utf8'));
const codes = [
  ...new Set(features.map((f) => isoCode(f.properties)).filter(Boolean)),
].sort();
const gridValue = new Map(codes.map((code, i) => [code, FIRST_COUNTRY + i]));

const shapesOf = (feature) => {
  const code = isoCode(feature.properties);
  return {
    geometry: feature.geometry,
    value: code ? gridValue.get(code) : OTHER_LAND,
  };
};
const allShapes = prepareShapes(features.map(shapesOf));

/**
 * Natural Earth's label point: of the feature that is the country itself when
 * several share its code (Australia, not its Indian Ocean territories).
 */
const labels = new Map();
for (const feature of features) {
  const code = isoCode(feature.properties);
  if (code && (!labels.has(code) || feature.properties.ISO_A2 === code)) {
    labels.set(code, [feature.properties.LABEL_X, feature.properties.LABEL_Y]);
  }
}

const pack = (bytes) =>
  brotliCompressSync(bytes, {
    params: { [constants.BROTLI_PARAM_QUALITY]: 11 },
  }).toString('base64');

const variant = (name) => {
  const spec = WINDOWS[name];
  const size = { cols: spec.cols, rows: spec.rows };
  const world = worldGrid(spec.cellsPerDegree);
  const started = Date.now();
  const grid = rasterise(allShapes, world, { col: 0, row: 0 }, world);
  console.log(
    `${name}: world grid in ${Math.round((Date.now() - started) / 1000)}s`,
  );

  const windows = {};
  for (const code of codes) {
    const value = gridValue.get(code);
    const own = allShapes.filter((shape) => shape.value === value);
    const zoomedGrid = (zoom) => worldGrid(spec.cellsPerDegree * zoom);
    const originAt = (zoom) =>
      windowOrigin(toCell(zoomedGrid(zoom), labels.get(code)), spec);
    const zoom = pickZoom((zoom) => {
      const cells =
        zoom === 1
          ? extractWindow(grid, world, originAt(1), size)
          : rasterise(own, zoomedGrid(zoom), originAt(zoom), size);
      return cells.filter((cell) => cell === value).length;
    }, ZOOM);
    if (zoom === 1) {
      const { col, row } = originAt(1);
      windows[code] = [col, row];
      continue;
    }
    const cells = markOwn(
      rasterise(allShapes, zoomedGrid(zoom), originAt(zoom), size),
      value,
    );
    ensureOwnDot(cells, spec);
    windows[code] = pack(encodeRuns(cells));
    const dots = cells.filter((cell) => cell === CELL.own).length;
    console.log(`${name}: ${code} zoomed x${zoom} (${dots} dots)`);
  }
  return { grid: pack(encodeRuns(grid)), rows: world.rows, windows };
};

const desktop = variant('desktop');
const phone = variant('phone');

const body = `/**
 * Generated by scripts/generate-dot-maps.mjs from Natural Earth admin-0
 * countries (1:50m, public domain). Do not edit; re-run the script.
 *
 * Server only: the page gets one window's SVG paths, never this data.
 */
import type { DotMapDataset } from './grid';

export const DOT_MAP_DATASET: DotMapDataset = ${JSON.stringify({ codes, desktop, phone })};
`;
writeFileSync(target, body);
console.log(`Wrote ${target} (${Math.round(body.length / 1024)} KB)`);
