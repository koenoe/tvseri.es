/**
 * Generates src/components/ui/icon/glyphs.tsx from the approved SVGs in
 * apps/web/design/icons (one file per glyph, 24-unit viewBox).
 * Re-run after the icons are re-synced:
 *
 *   node apps/web/scripts/generate-icons.mjs && pnpm format-and-lint:fix
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../../..');
const source = path.join(root, 'apps/web/design/icons');
const target = path.join(root, 'apps/web/src/components/ui/icon/glyphs.tsx');

// The "on" drawing of a toggle, keyed by its outline file.
const FILLED = {
  bookmark: 'bookmark-filled',
  eye: 'eye-filled',
  heart: 'heart-filled',
  star: 'star-filled',
  'user-plus': 'user-check',
};
const filledFiles = new Set(Object.values(FILLED));
// user-check is also drawn on its own (followers) per icons_final.md.
filledFiles.delete('user-check');

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const jsxAttr = (name) =>
  ({ 'fill-rule': 'fillRule', 'stroke-width': 'strokeWidth' })[name] ?? name;

function children(file) {
  const svg = readFileSync(path.join(source, `${file}.svg`), 'utf8').trim();
  const inner = svg
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>$/, '')
    .replace(/><\/(path|circle|rect)>/g, '/>');
  const elements = [...inner.matchAll(/<(path|circle|rect)([^>]*?)\/>/g)];
  const rebuilt = elements.map((m) => m[0]).join('');
  if (rebuilt !== inner) {
    throw new Error(`${file}.svg has markup the generator doesn't handle`);
  }
  const jsx = elements.map(([, tag, attrs]) => {
    const props = [...attrs.matchAll(/([a-z-]+)="([^"]*)"/g)]
      .map(([, name, value]) => `${jsxAttr(name)}="${value}"`)
      .join(' ');
    return `<${tag} ${props} />`;
  });
  return jsx.length === 1 ? jsx[0] : `<>${jsx.join('')}</>`;
}

const files = readdirSync(source)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .filter((file) => !filledFiles.has(file))
  .sort();

// `@public`: a library of glyphs, pages import what they draw (knip).
const body = files
  .map((file) => {
    const filled = FILLED[file];
    const type = filled ? 'ToggleGlyph' : 'Glyph';
    const parts = [`outline: ${children(file)},`];
    if (filled) {
      parts.push(`filled: ${children(filled)},`);
    }
    return `/** @public */\nexport const ${camel(file)}Glyph: ${type} = { ${parts.join(' ')} };`;
  })
  .join('\n\n');

writeFileSync(
  target,
  `// Generated by apps/web/scripts/generate-icons.mjs from
// apps/web/design/icons. Don't edit by hand: re-sync the SVGs and
// re-run the script. Meanings and context variants: icons_final.md.

import type { Glyph, ToggleGlyph } from './types';

${body}
`,
);
console.log(`${files.length} glyphs written to ${path.relative(root, target)}`);
