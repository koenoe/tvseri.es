/// <reference path="../.sst/platform/config.d.ts" />

import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { apiRouter } from './api';
import { auth } from './auth';
import { domain, zone } from './dns';
import * as secrets from './secrets';

const VERCEL_TOKEN = process.env.VERCEL_API_TOKEN;
const VERCEL_TEAM_ID = process.env.VERCEL_TEAM_ID;

if (!$dev && !VERCEL_TOKEN) {
  throw new Error('VERCEL_API_TOKEN environment variable is required');
}
if (!$dev && !VERCEL_TEAM_ID) {
  throw new Error('VERCEL_TEAM_ID environment variable is required');
}

const isProduction = $app.stage === 'production';
const customDomain = isProduction ? 'www.tvseri.es' : `www.${domain}`;
const siteUrl = `https://${customDomain}`;
const projectName = isProduction ? 'tvseries' : `tvseries-${$app.stage}`;

// Pinned: an unpinned `npx vercel` takes whatever was released that day, and
// 66.6.0 deployed a preview whose functions ran without the project's
// environment variables. Raise it on purpose, after a preview deploy works.
const VERCEL_CLI = 'vercel@66.5.0';

/** One id per deploy (the commit, made unique by the time), for `NEXT_DEPLOYMENT_ID` */
const deploymentId = () =>
  `${(process.env.GITHUB_SHA ?? 'local').slice(0, 12)}-${Date.now().toString(36)}`;

function runVercel(
  command: string,
  projectId: string,
  options: { env?: Record<string, string>; capture?: boolean } = {},
) {
  const scopeFlag = VERCEL_TEAM_ID ? ` --scope=${VERCEL_TEAM_ID}` : '';

  // The token goes through the environment, never the command line, because a
  // failed execSync puts the full command in the error and the CI log.
  return execSync(`npx --yes ${VERCEL_CLI} ${command}${scopeFlag}`, {
    cwd: process.cwd(),
    encoding: 'utf-8',
    env: {
      ...process.env,
      ...options.env,
      VERCEL_ORG_ID: VERCEL_TEAM_ID,
      VERCEL_PROJECT_ID: projectId,
      VERCEL_TOKEN,
    },
    stdio: options.capture ? 'pipe' : 'inherit',
  });
}

if ($dev) {
  $resolve([
    apiRouter.url,
    auth.url,
    secrets.apiKeyRandom.result,
    secrets.sessionSecret.value,
  ]).apply(([apiUrl, authUrl, apiKey, secretKey]) => {
    const envContent = `# Auto-generated by SST dev - do not commit
API_KEY="${apiKey}"
API_URL=${apiUrl}
AUTH_URL=${authUrl}
SECRET_KEY="${secretKey}"
`;
    const envPath = path.join(process.cwd(), 'apps/web/.env.local');
    fs.writeFileSync(envPath, envContent);
    console.log(`|  Generated ${envPath}`);
  });

  new sst.x.DevCommand('Website', {
    dev: {
      // The extension's zip first, as `pnpm build` does (/extension links
      // it). Through the package script: SST runs the command without a
      // shell, so an `&&` here would reach node as arguments
      command: 'pnpm dev',
      directory: 'apps/web',
      title: 'Website',
    },
  });
}

export const web = $dev
  ? { url: 'http://localhost:3000' }
  : (() => {
      const project = new vercel.Project('WebProject', {
        framework: 'nextjs',
        name: projectName,
        resourceConfig: {
          // One region, next to the API in eu-west-2 (London)
          functionDefaultCpuType: 'standard',
          functionDefaultRegions: ['lhr1'],
        },
        rootDirectory: 'apps/web',
      });

      // Firewall/bot protection (BotID, JA3/JA4, OWASP sqli/xss/rce/gen, AI bots, custom "Scrobble" allow rule for
      // /api/webhooks/scrobble/plex) is managed in the Vercel dashboard. Don't manage it from code (vercel.FirewallConfig)
      // without importing those rules first, or applying it would wipe them and break Plex scrobbles.

      const vercelTarget = isProduction ? 'production' : 'preview';

      const vercelVariables = [
        {
          key: 'API_KEY',
          name: 'ApiKey',
          sensitive: true,
          value: secrets.apiKeyRandom.result,
        },
        { key: 'API_URL', name: 'ApiUrl', value: apiRouter.url },
        { key: 'AUTH_URL', name: 'AuthUrl', value: auth.url },
        {
          key: 'SECRET_KEY',
          name: 'SecretKey',
          sensitive: true,
          value: secrets.sessionSecret.value,
        },
        { key: 'SITE_URL', name: 'SiteUrl', value: siteUrl },
      ];

      const envVars = vercelVariables.map(
        (v) =>
          new vercel.ProjectEnvironmentVariable(
            `WebEnv${v.name}`,
            {
              comment:
                'This var is being managed by SST, do not edit or delete it via the Vercel dashboard',
              key: v.key,
              projectId: project.id,
              sensitive: v.sensitive,
              targets: [vercelTarget],
              value: v.value,
            },
            { deleteBeforeReplace: true },
          ),
      );

      const deployedUrl = $resolve([
        apiRouter.url,
        // Resolves once the API's distribution is deployed (see the wait below)
        apiRouter.distributionID,
        auth.url,
        secrets.apiKeyRandom.result,
        secrets.sessionSecret.value,
        project.id,
        ...envVars.map((e) => e.id),
      ]).apply(([apiUrl, , authUrl, apiKey, secretKey, projectId]) => {
        // Pulumi runs apply callbacks during previews (`sst diff`) too: never build/deploy/alias there.
        if ($util.runtime.isDryRun()) return siteUrl;

        const prodFlag = isProduction ? ' --prod' : '';
        const environment = isProduction ? 'production' : 'preview';

        // The build prerenders against the API, so wait until the API
        // answers with this deploy's key: a new stage's domain and routes are
        // created in this same deploy, and a replaced key reaches the edge
        // minutes after it changes. An unknown username is the API's 404;
        // the edge refusing the key is a 401, so that keeps waiting.
        console.log('|  Waiting for the API to accept the key...');
        execSync(
          'for i in $(seq 1 60); do code=$(curl -s -o /dev/null -w "%{http_code}" -H "x-api-key: $API_KEY" "$API_URL/user/by-username/deploy-probe"); [ "$code" = "404" ] && exit 0; sleep 5; done; echo "API not accepting the key after 5 minutes (last: $code)"; exit 1',
          {
            env: { ...process.env, API_KEY: apiKey, API_URL: apiUrl },
            shell: '/bin/bash',
            stdio: 'inherit',
          },
        );

        console.log('|  Pulling Vercel project settings...');
        runVercel(`pull --yes --environment=${environment}`, projectId);

        console.log('|  Building Next.js app...');
        runVercel(`build${prodFlag}`, projectId, {
          env: {
            API_KEY: apiKey,
            API_URL: apiUrl,
            AUTH_URL: authUrl,
            // A prebuilt build has no Vercel deployment id, so without one
            // of ours Skew Protection does nothing: a tab open across a
            // deploy calls Server Actions the new build no longer has
            NEXT_DEPLOYMENT_ID: deploymentId(),
            SECRET_KEY: secretKey,
            SITE_URL: siteUrl,
          },
        });

        console.log('|  Deploying to Vercel...');
        const deploymentUrl = runVercel(
          `deploy --prebuilt${prodFlag} --archive=tgz`,
          projectId,
          { capture: true },
        ).trim();
        console.log(`|  Deployed to ${deploymentUrl}`);

        runVercel(`alias set ${deploymentUrl} ${customDomain}`, projectId);
        console.log(`|  Live at ${siteUrl}`);

        return siteUrl;
      });

      if (isProduction) {
        new vercel.ProjectDomain('WebDomainWww', {
          domain: 'www.tvseri.es',
          projectId: project.id,
        });

        new aws.route53.Record('WwwVercelRecord', {
          allowOverwrite: true,
          name: 'www.tvseri.es',
          records: ['cname.vercel-dns.com'],
          // The target never changes; a longer TTL means fewer Route 53 queries
          ttl: 3600,
          type: 'CNAME',
          zoneId: zone,
        });

        // The apex redirects to www. An SST Cdn rather than a bare
        // distribution, so SST owns the certificate's lifecycle.
        const redirectFunction = new aws.cloudfront.Function(
          'ApexRedirectFunction',
          {
            code: `function handler(event) {
  return {
    statusCode: 301,
    statusDescription: 'Moved Permanently',
    headers: { location: { value: 'https://www.tvseri.es' + event.request.uri } }
  };
}`,
            name: 'tvseries-apex-redirect-to-www',
            runtime: 'cloudfront-js-2.0',
          },
        );

        new sst.aws.Cdn('ApexRedirect', {
          defaultCacheBehavior: {
            allowedMethods: ['GET', 'HEAD'],
            cachedMethods: ['GET', 'HEAD'],
            forwardedValues: {
              cookies: { forward: 'none' },
              queryString: false,
            },
            functionAssociations: [
              {
                eventType: 'viewer-request',
                functionArn: redirectFunction.arn,
              },
            ],
            targetOriginId: 'dummy',
            viewerProtocolPolicy: 'redirect-to-https',
          },
          domain: {
            dns: sst.aws.dns({ zone }),
            name: 'tvseri.es',
          },
          origins: [
            {
              customOriginConfig: {
                httpPort: 80,
                httpsPort: 443,
                originProtocolPolicy: 'https-only',
                originSslProtocols: ['TLSv1.2'],
              },
              domainName: 'www.tvseri.es',
              originId: 'dummy',
            },
          ],
        });
      } else {
        // Preview: www.pr-{n}.dev.tvseri.es -> Vercel
        new aws.route53.Record('PreviewWebRecord', {
          allowOverwrite: true,
          name: customDomain,
          records: ['cname.vercel-dns.com'],
          ttl: 300,
          type: 'CNAME',
          zoneId: zone,
        });
      }

      return { url: deployedUrl };
    })();
