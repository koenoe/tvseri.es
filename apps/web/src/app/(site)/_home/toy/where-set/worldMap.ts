/**
 * The projection: equirectangular over longitude -128 to 118 and
 * latitude 70 to -36, the same scale on both axes (680 / 246 = 293 / 106),
 * derived from its five pins (Baltimore at 142.1, 84.9 …).
 */
const WEST = -128;
const NORTH = 70;
const SCALE = MAP_WIDTH / 246;

export type MapPoint = Readonly<{ x: number; y: number }>;

/** A place on the map, or undefined when it falls outside it */
export const projectToMap = (
  lat: number,
  lng: number,
): MapPoint | undefined => {
  const x = (lng - WEST) * SCALE;
  const y = (NORTH - lat) * SCALE;
  return x >= 0 && x <= MAP_WIDTH && y >= 0 && y <= MAP_HEIGHT
    ? { x, y }
    : undefined;
};
