/**
 * Generates the Stats page's dotted world map ("Where the series are from"): a 136 × 84 grid of dots over a 580 × 358 box, each cell
 * sea, land or a country (ISO 3166-1 alpha-2). Run when the map data changes:
 *
 *   node scripts/generate-stats-world-dots.mjs [<reference file with the dots>]
 *
 * With the reference file, its dots are the land mask (which cells have a
 * dot), so the map matches it dot for dot; Natural
 * Earth only says which country a cell belongs to (a board dot Natural Earth
 * puts in the sea is land without a country).
 *
 * Natural Earth 1:110m (world-atlas) in Web Mercator, sampled at cell
 * centres. Scale and translate were fitted to the reference dots (93% of
 * cells agree). Antarctica is left out, as in the reference. Alpha-2 codes come
 * from the feature's English name matched to Intl's region names (the names
 * the API's country stats use), plus a few aliases where they differ.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

import { geoContains, geoMercator } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const world = require('world-atlas/countries-110m.json');

const COLS = 136;
const ROWS = 84;
const WIDTH = 580;
const HEIGHT = 358;
const ANTARCTICA = '010';

const names = new Intl.DisplayNames(['en'], { type: 'region' });
const alpha2ByName = new Map();
for (let a = 65; a <= 90; a++) {
  for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a, b);
    const name = names.of(code);
    // Current codes only: deprecated ones (DD, CS, YD) and reserved ones
    // (UK) carry the same English names, and ICU canonicalises them away
    const canonical =
      Intl.getCanonicalLocales(`und-${code}`)[0] === `und-${code}`;
    if (canonical && name && name !== code && !alpha2ByName.has(name)) {
      alpha2ByName.set(name, code);
    }
  }
}
/** world-atlas names that differ from Intl's English names */
const ALIASES = {
  'Bosnia and Herz.': 'BA',
  'Central African Rep.': 'CF',
  Congo: 'CG',
  "Côte d'Ivoire": 'CI',
  'Dem. Rep. Congo': 'CD',
  'Dominican Rep.': 'DO',
  'Eq. Guinea': 'GQ',
  eSwatini: 'SZ',
  'Falkland Is.': 'FK',
  'Fr. S. Antarctic Lands': 'TF',
  Macedonia: 'MK',
  Myanmar: 'MM',
  Palestine: 'PS',
  'S. Sudan': 'SS',
  'Solomon Is.': 'SB',
  'Trinidad and Tobago': 'TT',
  Turkey: 'TR',
  'United States of America': 'US',
  'W. Sahara': 'EH',
};
const alpha2Of = (country) =>
  ALIASES[country.properties.name] ??
  alpha2ByName.get(country.properties.name) ??
  null;

const countries = feature(world, world.objects.countries).features.filter(
  (country) => country.id !== ANTARCTICA,
);
const projection = geoMercator().scale(91.5).translate([269.5, 263.5]);

/** The reference dots as `col,row` cells, or null to use Natural Earth's land */
const boardLand = (() => {
  const file = process.argv[2];
  if (!file) {
    return null;
  }
  const svg = readFileSync(file, 'utf8').match(
    /<svg class="st-map".*?<\/svg>/s,
  )?.[0];
  if (!svg) {
    throw new Error(`No st-map svg in ${file}`);
  }
  const cells = new Set();
  for (const [, x, y] of svg.matchAll(/M([\d.]+) ([\d.]+)h0/g)) {
    const col = Math.round((Number(x) * COLS) / WIDTH - 0.5);
    const row = Math.round((Number(y) * ROWS) / HEIGHT - 0.5);
    cells.add(`${col},${row}`);
  }
  return cells;
})();

const codes = [];
const SEA = ' ';
const LAND = '#';
// One character per cell: a country is U+00C0 + its index in `codes`
let grid = '';
for (let row = 0; row < ROWS; row++) {
  for (let col = 0; col < COLS; col++) {
    const point = projection.invert([
      ((col + 0.5) * WIDTH) / COLS,
      ((row + 0.5) * HEIGHT) / ROWS,
    ]);
    const isLand = boardLand ? boardLand.has(`${col},${row}`) : null;
    const hit =
      isLand === false
        ? undefined
        : countries.find((country) => geoContains(country, point));
    const code = hit ? alpha2Of(hit) : null;
    if (isLand === false || (isLand === null && !hit)) {
      grid += SEA;
    } else if (!code) {
      grid += LAND;
    } else {
      let index = codes.indexOf(code);
      if (index < 0) {
        index = codes.push(code) - 1;
      }
      grid += String.fromCharCode(0xc0 + index);
    }
  }
}

const out = path.join(
  import.meta.dirname,
  '../src/app/(site)/u/[username]/stats/[year]/_components/map/worldDots.ts',
);
writeFileSync(
  out,
  `// Generated by apps/web/scripts/generate-stats-world-dots.mjs. Don't edit by hand.
// Natural Earth 1:110m (world-atlas), public domain.

export const COLS = ${COLS};
export const ROWS = ${ROWS};
export const WIDTH = ${WIDTH};
export const HEIGHT = ${HEIGHT};

/** Country of a cell: \`CODES[charCode - 0xc0]\` */
export const CODES: ReadonlyArray<string> = ${JSON.stringify(codes)};

/** ${COLS} × ${ROWS} cells, row by row: ' ' sea, '#' land without a code, else a country */
export const GRID = ${JSON.stringify(grid)};
`,
);
console.log(
  `${codes.length} countries, ${grid.replaceAll(SEA, '').length} land cells → ${out}`,
);
