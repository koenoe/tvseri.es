import { formatCodeLifetime } from './codeLifetime';

/**
 * The sign-in code email : the site's
 * dark ground edge to edge, “tvseri.es” as plain text, a thin rule down the
 * left of the column with a white segment beside the code, and the code as
 * the headline. Two short lines, nothing to click, no image, nothing hosted.
 *
 * Built for mail clients: tables and inline styles, system fonts, one small
 * `<style>` for Apple's data detectors and the phone sizes. The code is one
 * unbroken text run (a double-click selects it, Apple Mail + Safari offer
 * it for autofill) near the word “code”, and right after it at the end of the subject. Nothing
 * a client could turn into a link: the domain carries a zero-width
 * non-joiner before its dot, and `format-detection` is off.
 */

const FONT =
  "-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif";

const GROUND = '#1c2223';
const INK = '#ffffff';
const SOFT = '#c4c8c9';
const QUIET_INK = '#8d9394';
const RULE = '#5b6364';

const QUIET = 'Didn’t ask for it? Ignore this email.';

// Gmail and iOS link a domain in a text node; the joiner in its own span
// breaks the match without showing.
const WORDMARK =
  'tvseri<span style="font:inherit;color:inherit">&zwnj;.</span>es';

// Fills the inbox preview after the preheader, so it doesn't run on into
// the body text.
const PREVIEW_FILLER = '&#847;&zwnj;&nbsp;'.repeat(40);

// Phones: less ground around the column, a 40px code
const PHONE = `@media (max-width:480px){.em-pad{padding:40px 20px 48px!important}.em-code{font-size:40px!important;line-height:48px!important}}`;
const DETECTORS =
  'a[x-apple-data-detectors],.x-gmail-data-detectors,.x-gmail-data-detectors *{color:inherit!important;text-decoration:none!important;font:inherit!important;border:0!important}';

const table = (inner: string, style = '', attributes = '') =>
  `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0"${attributes} style="border-collapse:collapse;${style}">${inner}</table>`;

const row = (style: string, content: string, attributes = '') =>
  `<tr><td align="left"${attributes} style="${style}">${content}</td></tr>`;

const RULED = `border-left:1px solid ${RULE};padding:0 0 0 24px`;
const SPACER = `${RULED};height:24px;font-size:0;line-height:0`;

export type CodeEmail = Readonly<{
  html: string;
  subject: string;
  text: string;
}>;

export function renderCodeEmail({
  code,
  ttl,
}: Readonly<{
  /** Six digits, generated by the code provider */
  code: string;
  /** How long the code works, in seconds (`CODE_TTL`) */
  ttl: number;
}>): CodeEmail {
  // The code last, right after the word “code” (Apple Mail + Safari autofill)
  const subject = `Your tvseri.es sign-in code: ${code}`;
  const expiry = `It works for ${formatCodeLifetime(ttl)}.`;
  const line = `Your sign-in code. ${expiry}`;

  const ruled = table(
    row(SPACER, '&nbsp;') +
      row(
        `border-left:3px solid ${INK};padding:0 0 0 22px`,
        `<div class="em-code" style="font-family:${FONT};font-size:48px;line-height:56px;font-weight:700;letter-spacing:.16em;font-variant-numeric:tabular-nums;color:${INK}">${code}</div>`,
      ) +
      row(
        `${RULED};padding-top:16px;font-family:${FONT};font-size:16px;line-height:24px;color:${SOFT}`,
        line,
      ) +
      row(
        `${RULED};padding-top:40px;font-family:${FONT};font-size:13px;line-height:20px;color:${QUIET_INK}`,
        QUIET,
      ) +
      row(SPACER, '&nbsp;'),
  );
  const column = table(
    row(
      'padding:0 0 32px 0',
      `<span style="font-family:${FONT};font-size:18px;line-height:24px;font-weight:800;letter-spacing:-.01em;color:${INK}">${WORDMARK}</span>`,
    ) + row('', ruled),
    'max-width:480px',
  );
  const body = table(
    `<tr><td align="center" class="em-pad" style="padding:56px 24px 64px">${column}</td></tr>`,
    `background:${GROUND}`,
    ` bgcolor="${GROUND}"`,
  );

  const html = `<!doctype html>
<html lang="en" dir="ltr"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="dark"><meta name="supported-color-schemes" content="dark"><meta name="format-detection" content="telephone=no,date=no,address=no,email=no,url=no"><meta name="x-apple-disable-message-reformatting"><title>Your sign-in code</title><style>${DETECTORS}${PHONE}</style></head><body style="margin:0;padding:0;-webkit-text-size-adjust:100%;background:${GROUND}"><div style="display:none;max-height:0;overflow:hidden;mso-hide:all">${expiry}${PREVIEW_FILLER}</div>${body}</body></html>
`;

  const text = `${code}\n\n${line}\n\n${QUIET}\n`;

  return { html, subject, text };
}
