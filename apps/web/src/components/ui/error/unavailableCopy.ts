/**
 * The one sentence pattern for a part of a page that didn't load (a
 * failed row, the cast, a Settings section): plain and functional, no jokes.
 */
export const didNotLoad = (what: string): string => `${what} didn’t load.`;

/** Its second line: only that part failed. */
export const REST_IS_FINE = 'The rest of the page is fine.';
